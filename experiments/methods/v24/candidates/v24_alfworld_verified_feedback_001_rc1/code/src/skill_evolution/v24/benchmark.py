"""Explicit, context-local benchmark binding; importing the core loads no adapter.

The caller binds one adapter for a campaign or an offline module invocation.
Worker threads inherit a copied context in evolution._actors. No process-global
monkeypatches, inferred benchmark, or fallback ALFWorld implementation exist.
"""
from contextlib import contextmanager
from contextvars import ContextVar
from typing import Protocol
from pathlib import Path


class Benchmark(Protocol):
    identity: dict

    def validate_config(self, config: dict) -> None: ...
    def resource(self, key: str) -> Path: ...
    def frozen_files(self) -> dict[str, str]: ...
    def build_facts(self, records: list) -> dict: ...
    def parent_text(self, record: dict) -> str | None: ...
    def evidence(self, operation: str, *args, **kwargs): ...
    def plan_fields(self) -> tuple: ...
    def auxiliary_references(self, payload: dict) -> set: ...
    def validate_execution_source(self, source: dict) -> dict: ...
    def validation_sources(self) -> set[Path]: ...
    def actor_fields(self, template: str, background: dict) -> str: ...
    def execution_context(self, background: dict) -> str: ...
    def build_gate(self, *args, **kwargs) -> dict: ...
    def actor_task(self, task, skill_file, directory, config, *, final=False): ...
    def actor_command(self, task, skill_file, directory, config, *, final=False): ...
    def check_record(self, record, task, expected_skill, config) -> dict: ...
    def is_complete(self, record: dict) -> bool: ...
    def runtime_snapshot(self, config: dict) -> dict | None: ...
    def prepare_evaluation(self, experiment, campaign) -> dict: ...
    def check_evaluation_record(self, path, task, bundle) -> dict: ...


_benchmark = ContextVar('v24_benchmark')


def current() -> Benchmark:
    try:
        return _benchmark.get()
    except LookupError:
        raise RuntimeError('Bind a benchmark explicitly with using_benchmark(adapter)') from None


@contextmanager
def using_benchmark(adapter: Benchmark):
    token = _benchmark.set(adapter)
    try:
        yield adapter
    finally:
        _benchmark.reset(token)
