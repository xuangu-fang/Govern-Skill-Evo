def training_ls():
    # Every observation is generated by executing real sandbox tools, never prose labels.
    cases=[]
    for name,prices,elig,fault,channel in [
        ('S-A',[8000,18000,3000],[1,1,0],True,'online'),
        ('S-B',[8000,22000],[1,1],True,'online'),
        ('S-C',[5000,25000],[1,1],True,'online'),
        ('S-D',[5000,25000],[1,1],True,'store'),
        ('S-E',[5000,25000],[1,1],False,'online'),
        ('S-F',[10001,19999],[1,1],True,'online'),
        ('S-G',[10000,20000],[1,1],True,'online'),
        ('S-H',[8000,18000,11000],[1,1,0],True,'online'),
    ]:
        c=ls_case(name,prices,elig,[fault]+[False]*(len(prices)-1),[channel]+['online']*(len(prices)-1),[0],0,1,'train')
        cases.append(c)
    return cases


def training_lg():
    rows=[('G-A',('I',),'supplier',5*86400,'defect'),
          ('G-B',('I','V'),'supplier',5*86400,'defect'),
          ('G-C',('I','L'),'supplier',5*86400,'defect'),
          ('G-D',('W','V'),'supplier',5*86400,'defect'),
          ('G-E',('W','V'),'carrier',5*86400,'defect'),
          ('G-F',('W','V'),'supplier',10*86400,'defect'),
          ('G-G',('W','V'),'supplier',5*86400,'accidental'),
          ('G-H',('W',),'supplier',5*86400,'defect'),
          ('G-I',('I','V'),'supplier',5*86400,'accidental'),
          ('G-J',('W','V'),'supplier',604800,'defect'),
          ('G-K',('W','V'),'supplier',604801,'defect')]
    cases=[lg_case(n,k,i,a,r,'train') for n,k,i,a,r in rows]
    for name,field,value in [('G-L','order_id','other-order'),('G-M','authentic',False)]:
        c=lg_case(name,('I','V'),split='train')
        c['documents'][0][field]=value
        cases.append(c)
    return cases


