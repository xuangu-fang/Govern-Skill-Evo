def ls_case(name, prices, eligible, faults, channels, allowed, wallet, price, split='calibration_holdout'):
    ids=[f'{name}-item-{n+1}' for n in range(len(prices))]
    return dict(id=name,kind='LS1',world_version='sandbox-settlement-v1',split=split,order_id=f'order-{name}',
        items=[dict(id=i,price=p,eligible=bool(e),verified_supplier_fault=bool(f),original_channel=c)
               for i,p,e,f,c in zip(ids,prices,eligible,faults,channels)],
        allowed_returns=[ids[n] for n in allowed],return_channel='online',wallet=wallet,
        purchase={'id':f'new-{name}','price':price},warehouse_receipts=[])


def lg_case(name,kinds=('W','V','L'),issuer='supplier',age=3*86400,reason='defect',split='calibration_holdout'):
    c=dict(id=name,kind='LG1',world_version='sandbox-evidence-v1',split=split,
        order_id=f'order-{name}',reason=reason,receipt_time=1780000000,
        document_version='revision-1',auth_token=f'authority-{name}',endpoint=f'service://{name}/aftersales',
        application={'order_id':f'order-{name}','reason':reason,'requested_service':'aftersales_review'},
        supplement_availability={'I':'Inspection has not yet taken place if I is absent; no completed record can be obtained in this session.',
            'W':'Existing signed statement only; no replacement statement available in this session.',
            'V':'Only listed records are currently available. Supplement requests receive a tracking receipt.',
            'L':'Only listed records are currently available.'})
    c['documents']=[dict(id=f'{name}-doc-{k}',kind=k,issuer=issuer if k=='W' else 'supplier',
        issued_at=c['receipt_time']-(age if k=='W' else 2*86400),authentic=True,
        order_id=c['order_id'],version=c['document_version'],purpose='aftersales') for k in kinds]
    return c


